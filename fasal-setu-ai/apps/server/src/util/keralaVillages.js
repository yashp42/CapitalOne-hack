// Get all districts in Kerala
export const getKeralaDistricts = () => {
    const data = loadKeralaVillages();
    const districts = [...new Set(data.records.map(record => record.district))].sort();
    return districts;
};

// Get villages for a specific district
export const getVillagesForDistrict = (district) => {
    const data = loadKeralaVillages();
    return data.records
        .filter(record => record.district === district)
        .map(record => ({
            village: record.village,
            lat: record.lat,
            lon: record.lon
        }))
        .sort((a, b) => a.village.localeCompare(b.village));
};

// Get coordinates for a specific village in a district
export const getVillageCoordinates = (district, village) => {
    const data = loadKeralaVillages();
    const record = data.records.find(
        record => record.district === district && 
                 record.village.toLowerCase() === village.toLowerCase()
    );
    
    if (record) {
        return {
            lat: record.lat,
            lon: record.lon,
            found: true
        };
    }
    
    return {
        lat: null,
        lon: null,
        found: false
    };
};

// Validate if a district is a valid Kerala district
export const validateKeralaDistrict = (district) => {
    const districts = getKeralaDistricts();
    return districts.includes(district);
};

// Validate if a village exists in the given Kerala district
export const validateKeralaVillage = (district, village) => {
    const coordinates = getVillageCoordinates(district, village);
    return coordinates.found;
};

// Validate if a village exists in the given district (legacy function name)
export const validateVillage = (district, village) => {
    const coordinates = getVillageCoordinates(district, village);
    return coordinates.found;
};

// Get all villages (for search functionality)
export const getAllVillages = () => {
    const data = loadKeralaVillages();
    return data.records.map(record => ({
        district: record.district,
        village: record.village,
        lat: record.lat,
        lon: record.lon
    }));
};

// Search villages by name (fuzzy matching)
export const searchVillages = (searchTerm) => {
    const data = loadKeralaVillages();
    const term = searchTerm.toLowerCase();
    
    return data.records
        .filter(record => 
            record.village.toLowerCase().includes(term) ||
            record.district.toLowerCase().includes(term)
        )
        .map(record => ({
            district: record.district,
            village: record.village,
            lat: record.lat,
            lon: record.lon
        }))
        .sort((a, b) => a.village.localeCompare(b.village));
};